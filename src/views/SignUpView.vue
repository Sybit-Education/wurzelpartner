<script setup lang="ts">
import { ref } from 'vue'
import { useRouter } from 'vue-router'
import { UserInfoService } from '@/services/userInfoService'
import PasswordInput from '@/components/common/PasswordInput.vue'
import type { UserInfo } from '@/models/userInfo'

const userService = new UserInfoService()
const router = useRouter()

const username = ref('')
const email = ref('')
const password = ref('')
const confirmPassword = ref('')
const errorMessage = ref('')
const loading = ref(false)

const handleSignUp = async (event: Event) => {
  try {
    event.preventDefault()
    loading.value = true
    errorMessage.value = ''

    // Validierung
    if (!username.value || !email.value || !password.value) {
      errorMessage.value = 'Bitte füllen Sie alle Felder aus.'
      return
    }

    if (password.value !== confirmPassword.value) {
      errorMessage.value = 'Die Passwörter stimmen nicht überein.'
      return
    }

    // Passwortanforderungen prüfen
    const passwordRegex = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$/
    if (!passwordRegex.test(password.value)) {
      errorMessage.value =
        'Das Passwort muss mindestens 8 Zeichen lang sein und mindestens einen Großbuchstaben, einen Kleinbuchstaben, eine Zahl und ein Sonderzeichen enthalten.'
      return
    }

    // Benutzer erstellen
    const newUser = {
      username: username.value,
      email: email.value,
      password: password.value,
    }

    // The id will be generated by the server
    const createdUser = await userService.createUser(newUser as unknown as UserInfo)

    if (createdUser) {
      // Erfolgreiche Registrierung
      // Weiterleitung zur Anmeldeseite
      router.push('/login')
    } else {
      errorMessage.value = 'Bei der Registrierung ist ein Fehler aufgetreten.'
    }
  } catch (error) {
    console.error('Registrierungsfehler:', error)
    errorMessage.value =
      'Bei der Registrierung ist ein Fehler aufgetreten. Bitte versuchen Sie es später erneut.'
  } finally {
    loading.value = false
  }
}
</script>

<template>
  <div class="auth-card">
    <div class="form-stack p-surface">
      <h1 class="text-xl font-bold leading-tight tracking-tight text-heading md:text-2xl">
        Konto erstellen
      </h1>
      <form @submit="handleSignUp" class="form-stack">
        <div>
          <label for="username" class="form-label"> Benutzername </label>
          <input
            type="text"
            name="username"
            id="username"
            v-model="username"
            class="form-input"
            required
          />
        </div>
        <div>
          <label for="email" class="form-label">Ihre E-Mail</label>
          <input type="email" name="email" id="email" v-model="email" class="form-input" required />
        </div>
        <div>
          <PasswordInput
            v-model="password"
            id="password"
            name="password"
            label="Passwort"
            :required="true"
            autocomplete="new-password"
          />
        </div>
        <div>
          <PasswordInput
            v-model="confirmPassword"
            id="confirmPassword"
            name="confirmPassword"
            label="Passwort bestätigen"
            :required="true"
            autocomplete="new-password"
          />
        </div>
        <div>
          <p v-if="errorMessage" class="form-error">
            {{ errorMessage }}
          </p>
        </div>
        <button type="submit" class="auth-submit" :disabled="loading">
          <span v-if="loading">Wird registriert...</span>
          <span v-else>Registrieren</span>
        </button>
        <p class="text-sm font-light text-muted">
          Bereits registriert?
          <router-link
            to="/login"
            class="font-medium text-primary-600 hover:underline dark:text-primary-500"
            >Anmelden</router-link
          >
        </p>
      </form>
    </div>
  </div>
</template>
